import math
print(f"π = {math.pi}")
print(f"Raíz de 144: {math.sqrt(144)}")
print(f"Hacia arriba (4.1): {math.ceil(4.1)}")
print(f"Hacia abajo (4.9): {math.floor(4.9)}")
cateto1 = 3
cateto2 = 4
hipotenusa = math.sqrt(cateto1 ** 2 + cateto2 ** 2)
print(f"Cateto 1: {cateto1}")
